class TranslationService {
  constructor() {
    this.currentLanguage = this.getStoredLanguage()
    this.listeners = []
  }

  getStoredLanguage() {
    try {
      return localStorage.getItem('preferredLanguage') || 'en'
    } catch (error) {
      return 'en'
    }
  }

  setLanguage(lang) {
    this.currentLanguage = lang
    try {
      localStorage.setItem('preferredLanguage', lang)
    } catch (error) {
      console.warn('Could not save language preference:', error)
    }
    
    // 🔥 DISPARAR EVENTO SINCRONAMENTE - SEM setTimeout
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }))
    
    // 🔥 NOTIFICAR TODOS OS LISTENERS
    this.listeners.forEach(listener => listener(lang))
  }

  getLanguage() {
    return this.currentLanguage
  }

  subscribe(listener) {
    this.listeners.push(listener)
    return () => {
      this.listeners = this.listeners.filter(l => l !== listener)
    }
  }

  t(key) {
    if (!key || typeof key !== 'string') return ''

    const translation = translations[key]
    if (!translation) {
      console.warn(`Translation key not found: "${key}"`)
      return key
    }

    const translated = translation[this.currentLanguage]
    if (!translated) {
      return translation.en || key
    }

    return translated
  }
}


export const translationService = new TranslationService()
export const setLanguage = (lang) => translationService.setLanguage(lang)
export const getLanguage = () => translationService.getLanguage()
export const t = (key) => translationService.t(key)